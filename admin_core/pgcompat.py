"""SQLite locally, Neon Postgres when DATABASE_URL is set. No secrets logged."""
from __future__ import annotations

import os
import re
import sqlite3
from collections.abc import Mapping
from contextlib import suppress
from pathlib import Path
from urllib.parse import urlparse, urlunparse, parse_qsl, urlencode

def _database_url() -> str:
    return os.environ.get("DATABASE_URL") or os.environ.get("POSTGRES_URL") or ""


def use_postgres() -> bool:
    return bool(_database_url())


def backend_name() -> str:
    return "postgres" if use_postgres() else "sqlite"


def pooled_url(url: str) -> str:
    if not url or "-pooler." in url:
        return url
    parsed = urlparse(url)
    host = parsed.hostname or ""
    if host.startswith("ep-") and ".neon.tech" in host:
        host = host.replace(".neon.tech", "-pooler.neon.tech", 1) if "-pooler" not in host else host
        # Neon pooled host is typically ep-xxx-pooler.region.aws.neon.tech
        parts = host.split(".")
        if parts and "-pooler" not in parts[0]:
            parts[0] = parts[0] + "-pooler"
            host = ".".join(parts)
        netloc = parsed.netloc.replace(parsed.hostname or "", host, 1)
        return urlunparse((parsed.scheme, netloc, parsed.path, parsed.params, parsed.query, parsed.fragment))
    return url


def postgres_schema(script: str) -> str:
    parts = []
    for stmt in script.split(";"):
        s = stmt.strip()
        if not s or s.upper().startswith("PRAGMA"):
            continue
        s = re.sub(
            r"\bINTEGER PRIMARY KEY\b",
            "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            s,
            flags=re.I,
        )
        parts.append(s)
    return ";\n".join(parts) + ";"


def _adapt_sql(sql: str) -> str:
    out = sql
    out = re.sub(r'=\s*"([^"]*)"', lambda m: "='" + m.group(1).replace("'", "''") + "'", out)
    out = re.sub(r'!=\s*""', "!= ''", out)
    out = out.replace("?", "%s")
    return out


class _PgRow(Mapping):
    __slots__ = ("_names", "_values", "_map")

    def __init__(self, names, values):
        self._names = list(names)
        self._values = list(values)
        self._map = {n: v for n, v in zip(self._names, self._values)}

    def __getitem__(self, key):
        if isinstance(key, int):
            return self._values[key]
        return self._map[key]

    def keys(self):
        return self._map.keys()

    def __iter__(self):
        return iter(self._names)

    def __len__(self):
        return len(self._names)

    def __contains__(self, key):
        return key in self._map


class _PgCursor:
    def __init__(self, cur, names, lastrowid=None):
        self._cur = cur
        self._names = names or []
        self.lastrowid = lastrowid

    def fetchone(self):
        row = self._cur.fetchone()
        if row is None:
            return None
        return _PgRow(self._names, row)

    def fetchall(self):
        return [_PgRow(self._names, r) for r in self._cur.fetchall()]


class PostgresConnection:
    def __init__(self, conn):
        self._conn = conn
        self.lastrowid = None

    def execute(self, sql, params=()):
        raw = sql.strip()
        if raw.upper().startswith("PRAGMA TABLE_INFO"):
            table = raw[raw.find("(") + 1 : raw.rfind(")")].strip().strip("'\"")
            cur = self._conn.cursor()
            cur.execute(
                "SELECT column_name AS name, 'TEXT' AS type FROM information_schema.columns "
                "WHERE table_schema='public' AND table_name=%s ORDER BY ordinal_position",
                (table.lower(),),
            )
            names = [d[0] for d in (cur.description or [])]
            return _PgCursor(cur, names, None)
        if raw.upper().startswith("PRAGMA"):
            class _Empty:
                def fetchall(self):
                    return []
                def fetchone(self):
                    return None
                lastrowid = None
            return _Empty()
        sql2 = _adapt_sql(sql)
        returning = False
        if sql2.lstrip().upper().startswith("INSERT") and "RETURNING" not in sql2.upper():
            # sessions uses id_hash PK; still safe if table has identity id
            if re.search(r"INSERT\s+INTO\s+sessions\b", sql2, re.I) is None:
                sql2 = sql2.rstrip().rstrip(";") + " RETURNING id"
                returning = True
        cur = self._conn.cursor()
        cur.execute(sql2, params or ())
        names = [d[0] for d in (cur.description or [])]
        last = None
        if returning:
            row = cur.fetchone()
            if row:
                last = row[0]
                self.lastrowid = last
                # re-wrap remaining as empty cursor after consuming returning row
                class _InsertCur:
                    def __init__(self, lastrowid):
                        self.lastrowid = lastrowid
                    def fetchone(self):
                        return None
                    def fetchall(self):
                        return []
                return _InsertCur(last)
        wrapper = _PgCursor(cur, names, last)
        return wrapper

    def executescript(self, script: str):
        for stmt in filter(None, (s.strip() for s in postgres_schema(script).split(";"))):
            if not stmt or stmt.startswith("--"):
                continue
            self.execute(stmt)

    def commit(self):
        self._conn.commit()

    def close(self):
        with suppress(Exception):
            self._conn.commit()
        self._conn.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            if exc_type:
                with suppress(Exception):
                    self._conn.rollback()
            else:
                self._conn.commit()
        finally:
            self.close()
        return False


def _connect_postgres():
    import ssl
    import pg8000.dbapi

    url = pooled_url(_database_url())
    u = urlparse(url)
    q = [(k, v) for k, v in parse_qsl(u.query) if k.lower() not in {"channel_binding"}]
    u = u._replace(query=urlencode(q))
    ssl_ctx = ssl.create_default_context()
    conn = pg8000.dbapi.connect(
        user=u.username,
        password=u.password,
        host=u.hostname,
        port=u.port or 5432,
        database=(u.path or "/neondb").lstrip("/"),
        ssl_context=ssl_ctx,
        timeout=30,
    )
    return PostgresConnection(conn)
