-- Additive migration for garakmall merchant onboarding/community.
-- Existing sales/demo tables and neon_auth schema are not modified.
CREATE TABLE IF NOT EXISTS public.merchant_applications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author_id TEXT NOT NULL,
  shop_name VARCHAR(80) NOT NULL,
  contact_name VARCHAR(50) NOT NULL,
  phone VARCHAR(30) NOT NULL,
  email VARCHAR(120) NOT NULL,
  category VARCHAR(60) NOT NULL,
  shop_location VARCHAR(120) NOT NULL DEFAULT '',
  description TEXT NOT NULL,
  consent_at TIMESTAMPTZ NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','reviewed','rejected')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  reviewed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS merchant_applications_author_created_idx ON public.merchant_applications(author_id,created_at DESC);
CREATE TABLE IF NOT EXISTS public.community_posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author_id TEXT NOT NULL,
  author_label VARCHAR(60) NOT NULL,
  category VARCHAR(16) NOT NULL CHECK(category IN ('notice','season','story','question')),
  title VARCHAR(120) NOT NULL,
  body TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  reviewed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS community_posts_public_idx ON public.community_posts(status,category,id DESC);
CREATE INDEX IF NOT EXISTS community_posts_author_idx ON public.community_posts(author_id,id DESC);
CREATE TABLE IF NOT EXISTS public.community_comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id BIGINT NOT NULL REFERENCES public.community_posts(id),
  author_id TEXT NOT NULL,
  author_label VARCHAR(60) NOT NULL,
  body TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  reviewed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS community_comments_public_idx ON public.community_comments(post_id,status,id);
CREATE INDEX IF NOT EXISTS community_comments_author_idx ON public.community_comments(author_id,created_at DESC);
